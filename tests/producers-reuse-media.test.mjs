import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const deps = await import(pathToFileURL(path.join(ROOT, 'scripts', 'dependencies-diff.mjs')).href);
const { packagePlaywright } = await import(pathToFileURL(path.join(ROOT, 'scripts', 'playwright-diff.mjs')).href);
const { normalizeConfig } = await import(pathToFileURL(path.join(ROOT, 'scripts', 'config.mjs')).href);

function write(root, rel, body) {
  const full = path.join(root, rel);
  mkdirSync(path.dirname(full), { recursive: true });
  writeFileSync(full, body);
}

describe('lockfile parsers', () => {
  it('reads yarn, pnpm, and Cargo locks', () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'diffbrief-locks-'));
    write(
      dir,
      'yarn.lock',
      `# yarn lockfile v1
lodash@^4.17.0:
  version "4.17.21"
  resolved "https://example"
"@scope/pkg@1.0.0":
  version "1.0.0"
`,
    );
    write(
      dir,
      'pnpm-lock.yaml',
      `lockfileVersion: '9.0'
packages:
  'lodash@4.17.21':
    resolution: {integrity: sha}
  '/@scope/pkg@2.0.0':
    resolution: {integrity: sha}
`,
    );
    write(
      dir,
      'Cargo.lock',
      `# This file is automatically @generated by Cargo.
[[package]]
name = "serde"
version = "1.0.210"
source = "registry+https://github.com/rust-lang/crates.io-index"
`,
    );
    const yarn = deps.collectYarnLock(path.join(dir, 'yarn.lock'));
    assert.equal(yarn.get('lodash'), '4.17.21');
    assert.equal(yarn.get('@scope/pkg'), '1.0.0');
    const pnpm = deps.collectPnpmLock(path.join(dir, 'pnpm-lock.yaml'));
    assert.equal(pnpm.get('lodash'), '4.17.21');
    assert.equal(pnpm.get('@scope/pkg'), '2.0.0');
    const cargo = deps.collectCargoLock(path.join(dir, 'Cargo.lock'));
    assert.equal(cargo.get('serde'), '1.0.210');

    write(dir, 'base/yarn.lock', `lodash@^4.0.0:
  version "4.0.0"
`);
    write(dir, 'head/yarn.lock', `lodash@^4.0.0:
  version "4.17.21"
`);
    write(dir, 'head/Cargo.lock', `[[package]]
name = "serde"
version = "1.0.210"
`);
    const result = deps.diffDependencies({
      baseRoot: path.join(dir, 'base'),
      headRoot: path.join(dir, 'head'),
    });
    assert.match(result.markdown, /yarn\.lock/);
    assert.match(result.markdown, /lodash/);
    assert.match(result.markdown, /Cargo\.lock/);
    assert.match(result.markdown, /serde/);
    rmSync(dir, { recursive: true, force: true });
  });
});

describe('playwright producer', () => {
  it('copies videos into the artifact tree and links them', () => {
    const dir = mkdtempSync(path.join(tmpdir(), 'diffbrief-pw-'));
    write(dir, 'head/test-results/login/video.webm', 'fake-video');
    write(dir, 'head/test-results/login/trace.zip', 'fake-trace');
    const out = path.join(dir, 'out');
    const result = packagePlaywright({
      headRoot: path.join(dir, 'head'),
      outDir: out,
    });
    assert.equal(result.copied.length, 2);
    assert.equal(existsSync(path.join(out, 'playwright', 'test-results', 'login', 'video.webm')), true);
    assert.match(result.markdown, /video\.webm/);
    assert.match(result.markdown, /trace\.zip/);
    assert.match(readFileSync(path.join(out, 'playwright', 'index.md'), 'utf8'), /Playwright media/);
    rmSync(dir, { recursive: true, force: true });
  });
});

describe('config', () => {
  it('accepts playwright and openapi.cacheSpecs', () => {
    const cfg = normalizeConfig({
      producers: [
        { type: 'openapi', cacheSpecs: true },
        { type: 'playwright', maxVideos: 3 },
        { type: 'dependencies' },
      ],
    });
    assert.equal(cfg.producers[0].cacheSpecs, true);
    assert.equal(cfg.producers[1].maxVideos, 3);
    assert.equal(cfg.producers[2].lockfiles, null);
  });
});
